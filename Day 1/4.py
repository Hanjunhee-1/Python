# 문제1. 자기소개 프로그램(기본)
'''
사용자로부터 이름(문자열), 나이(정수), 전공(문자열)을 입력받아 자기소개를 출력하는 프로그램 완성하기

ex)
안녕하세요. "이름"입니다. 나이는 "나이"살이고, 전공은 "전공"입니다.
'''
name = input("이름을 입력해주세요: ")
age = int(input("나이를 입력해주세요: "))
major = input("전공을 입력해주세요: ")

print("안녕하세요. {}입니다. 나이는 {}살이고, 전공은 {}입니다.".format(name, age, major))

# 문제2. 쇼핑 계산 프로그램
'''
요구사항
1. 상품의 가격을 입력받습니다.
2. 구매 수량을 입력받습니다.
3. 총 구매 금액을 계산합니다.
4. 총 구매 금액이 50,000원 이상이면 10% 할인합니다.
5. 최종 결제 금액을 출력합니다.
'''

price = int(input("상품 가격 입력: "))
quantity = int(input("구매 수량 입력: "))
total_price = price * quantity
if total_price >= 50000:
  total_price *= 0.9
print(f"최종 결제 금액: {round(total_price):,}원")